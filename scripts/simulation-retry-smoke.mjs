import { chromium,devices } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required']});
const context=await browser.newContext({...devices['Pixel 7']});const page=await context.newPage();const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.GAME_TEST_URL ?? 'http://127.0.0.1:8080/',{waitUntil:'networkidle'});await page.waitForFunction(()=>!!window.vettaru);
await page.evaluate(()=>{vettaru.screens.startRace(vettaru.PRACTICE_LEVEL);});
await page.waitForFunction(()=>!!vettaru.raceScreen,{timeout:15000});
await page.evaluate(()=>{window.oldRace=vettaru.raceScreen;oldRace.state.awaitingBriefing=false;oldRace.state.phase='racing';oldRace.race.phase='racing';vettaru.speech.stop();});
await page.keyboard.down('w');await page.keyboard.down('d');
await page.waitForFunction(()=>vettaru.raceScreen.state.awaitingRetry&&vettaru.raceScreen.state.paused,{timeout:45000});
await page.keyboard.up('w');await page.keyboard.up('d');
const crash=await page.evaluate(()=>({collisions:oldRace.state.collisions,elapsed:oldRace.state.elapsed,speed:oldRace.race.player.speed,position:[oldRace.race.player.x,oldRace.race.player.z],button:document.querySelector('#pause-panel button')?.textContent}));
assert.match(crash.button,/^Try again/);assert.equal(crash.speed,0);
await page.waitForTimeout(3500);
const stopped=await page.evaluate(()=>({elapsed:oldRace.state.elapsed,position:[oldRace.race.player.x,oldRace.race.player.z],same:vettaru.raceScreen===oldRace}));
assert.equal(stopped.elapsed,crash.elapsed);assert.deepEqual(stopped.position,crash.position);assert.equal(stopped.same,true);
await page.touchscreen.tap(160,380);await page.waitForTimeout(750);
assert.equal(await page.evaluate(()=>vettaru.raceScreen===oldRace),true,'single tap only confirms');
await page.touchscreen.tap(160,380);await page.waitForTimeout(140);await page.touchscreen.tap(160,380);await page.waitForTimeout(750);
assert.equal(await page.evaluate(()=>vettaru.raceScreen!==oldRace),true,'explicit double tap restarts');
assert.equal(await page.evaluate(()=>vettaru.raceScreen.state.awaitingRetry),false);
assert.deepEqual(errors,[]);
console.log(JSON.stringify({result:'PASS: original 3D simulation real driving into barrier stops, freezes and waits for actual phone double-tap Try again',crash,stopped,errors},null,2));
await browser.close();
